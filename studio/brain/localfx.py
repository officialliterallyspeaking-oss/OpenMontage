def photography_variants(
    source: str | Path,
    out_dir: str | Path,
    *,
    palette: Sequence[str],
    width: int = 1080,
    height: int = 1920,
    count: int = 4,
    narrate: str = "",
    focus: tuple[float, float] = (0.5, 0.45),
) -> list[dict]:
    """Real, derived frames from the user's own image.

    These are honest assets: crops and grades of a photograph the user supplied,
    not generated content. Provenance is recorded as ``source``.
    """
    source = Path(source)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    base = Image.open(source).convert("RGB")
    roles = palette_roles(list(palette))
    dark, light = hex_to_rgb(roles["base"]), hex_to_rgb(roles["ink"])
    accent = hex_to_rgb(roles["accent"])

    recipes = [
        ("wide", 1.0, 0.0, 1.02),
        ("detail", 1.55, 0.30, 1.0),
        ("macro", 2.30, 0.55, 1.0),
        ("air", 1.18, 0.12, 1.06),
        ("texture", 1.90, 0.80, 0.96),
    ]
    out: list[dict] = []
    for index in range(min(count, len(recipes))):
        name, zoom, bias, exposure = recipes[index]
        frame = _cover(base, (width, height))
        if zoom != 1.0:
            crop_w = int(width / zoom)
            crop_h = int(height / zoom)
            # centre the tighter crops on the measured focal point, nudged per
            # treatment so the four frames do not all land on the same detail
            cx = int(width * focus[0])
            cy = int(height * (focus[1] + (bias - 0.4) * 0.30))
            left = max(0, min(width - crop_w, cx - crop_w // 2))
            top = max(0, min(height - crop_h, cy - crop_h // 2))
            frame = frame.crop((left, top, left + crop_w, top + crop_h)).resize(
                (width, height), Image.Resampling.LANCZOS
            )
        frame = ImageEnhance.Brightness(frame).enhance(exposure)
        frame = ImageEnhance.Contrast(frame).enhance(1.06)
        frame = ImageEnhance.Color(frame).enhance(0.94)
        if index == 2:
            # macro frames get a duotone wash so the edit has tonal range
            tinted = ImageOps_colorize(frame, _mix(dark, (0, 0, 0), 0.2), light)
            frame = Image.blend(frame, tinted, 0.45)
        frame = _vignette(frame, 0.24)
        if narrate:
            frame = _photo_type_block(frame, name, narrate, index)
        path = out_dir / f"look_{index + 1:02d}_{name}.jpg"
        frame.save(path, quality=94, subsampling=1)
        out.append(
            {
                "path": str(path),
                "name": name,
                "treatment": f"crop {zoom:.2f}x · exposure {exposure:.2f}",
                "width": width,
                "height": height,
                "provenance": "source",
                "derived_from": str(source),
                "instructions": "derived from the uploaded photograph — no generative model",
            }
        )
    return out
