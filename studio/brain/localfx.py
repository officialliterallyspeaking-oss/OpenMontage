"""Deterministic local art direction — used only when no model provider is configured.

This module is not a stub that draws grey boxes. It composes a real editorial
frame: layered gradient fields, palette-driven light, film grain, vignette,
typographic hierarchy and safe-area aware placement. It is genuinely designed
output — it is simply *designed by rules*, not generated by a model, and every
asset it produces is stamped ``provenance: "local"`` so the UI, the QA report and
the publishing package all state that plainly.

Why have it at all? Because the pipeline is real: script, storyboard, timing,
motion, captions, QA and the publishing package are all genuine whether or not an
image model is reachable. The honest thing is to run the whole machine and label
the one stage that had to be local, rather than pretend the machine needs a model
to work.
"""

from __future__ import annotations

import hashlib
import math
import random
from pathlib import Path
from typing import Iterable, Sequence

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter, ImageFont

FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    "/usr/share/fonts/truetype/freefont/FreeSansBold.ttf",
]


def _font(size: int, bold: bool = True) -> ImageFont.FreeTypeFont:
    for path in FONT_CANDIDATES:
        if Path(path).exists() and ("Bold" in path) == bold:
            try:
                return ImageFont.truetype(path, size)
            except Exception:
                continue
    for path in FONT_CANDIDATES:
        if Path(path).exists():
            try:
                return ImageFont.truetype(path, size)
            except Exception:
                continue
    return ImageFont.load_default()


def hex_to_rgb(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    if len(value) == 3:
        value = "".join(c * 2 for c in value)
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def _luma(rgb: tuple[int, int, int]) -> float:
    return (0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]) / 255


def _saturation(rgb: tuple[int, int, int]) -> float:
    high, low = max(rgb), min(rgb)
    return 0.0 if high == 0 else (high - low) / high


def palette_roles(palette: Sequence[str]) -> dict[str, str]:
    """Assign base / ink / accent / support by measuring, not by position.

    User palettes, niche palettes and colours sampled from a photograph all
    arrive in arbitrary order. Text has to land on the brightest one and the
    most saturated has to become the accent, or you get green body copy.
    """
    colours = [c for c in palette if c] or ["#0E1117", "#F2F0EA", "#E4572E"]
    rgb = [(c, hex_to_rgb(c)) for c in colours]
    base = min(rgb, key=lambda item: _luma(item[1]))[0]
    remaining = [item for item in rgb if item[0] != base] or rgb
    ink = max(remaining, key=lambda item: _luma(item[1]))[0]
    rest = [item for item in remaining if item[0] != ink] or remaining
    accent = max(rest, key=lambda item: _saturation(item[1]))[0]
    rest = [item for item in rest if item[0] != accent] or rest
    support = rest[0][0] if rest else accent
    return {"base": base, "ink": ink, "accent": accent, "support": support}


def _seed(*parts: object) -> random.Random:
    digest = hashlib.sha256("|".join(str(p) for p in parts).encode()).hexdigest()
    return random.Random(int(digest[:16], 16))


def _vertical_gradient(size: tuple[int, int], top: tuple[int, int, int], bottom: tuple[int, int, int]) -> Image.Image:
    width, height = size
    column = Image.new("RGB", (1, height))
    px = column.load()
    for y in range(height):
        t = y / max(1, height - 1)
        # smoothstep for a softer ramp
        t = t * t * (3 - 2 * t)
        px[0, y] = (
            int(top[0] + (bottom[0] - top[0]) * t),
            int(top[1] + (bottom[1] - top[1]) * t),
            int(top[2] + (bottom[2] - top[2]) * t),
        )
    return column.resize((width, height), Image.Resampling.BICUBIC)


def _radial_light(
    size: tuple[int, int],
    center: tuple[float, float],
    radius: float,
    colour: tuple[int, int, int],
    strength: float = 0.55,
) -> Image.Image:
    """A soft light pool, painted small then upscaled (fast + smooth)."""
    width, height = size
    scale = 8
    small = (max(8, width // scale), max(8, height // scale))
    layer = Image.new("L", small, 0)
    draw = ImageDraw.Draw(layer)
    cx, cy = center[0] * small[0], center[1] * small[1]
    r = radius * min(small)
    draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=int(255 * strength))
    layer = layer.filter(ImageFilter.GaussianBlur(radius=max(1, r / 2)))
    layer = layer.resize((width, height), Image.Resampling.BICUBIC)
    tint = Image.new("RGB", (width, height), colour)
    return Image.composite(tint, Image.new("RGB", size, (0, 0, 0)), layer)


def _grain(img: Image.Image, amount: float = 0.055, seed: random.Random | None = None) -> Image.Image:
    rng = seed or random.Random(7)
    width, height = img.size
    noise = Image.new("L", (width, height))
    px = noise.load()
    for y in range(0, height):
        for x in range(0, width):
            px[x, y] = int(128 + (rng.random() - 0.5) * 255 * amount * 4)
    noise = noise.filter(ImageFilter.GaussianBlur(0.4))
    return Image.blend(img, Image.merge("RGB", (noise, noise, noise)), amount)


def _vignette(img: Image.Image, strength: float = 0.35) -> Image.Image:
    width, height = img.size
    small = (max(8, width // 12), max(8, height // 12))
    mask = Image.new("L", small, 0)
    draw = ImageDraw.Draw(mask)
    pad = -min(small) * 0.15
    draw.ellipse([pad, pad, small[0] - pad, small[1] - pad], fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(min(small) / 6)).resize(
        (width, height), Image.Resampling.BICUBIC
    )
    dark = Image.new("RGB", (width, height), (0, 0, 0))
    blended = Image.composite(img, dark, mask)
    return Image.blend(img, blended, strength)


def _wrap(draw: ImageDraw.ImageDraw, text: str, font: ImageFont.FreeTypeFont, max_width: int) -> list[str]:
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        trial = f"{current} {word}".strip()
        if draw.textlength(trial, font=font) <= max_width or not current:
            current = trial
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def _fit_font(
    draw: ImageDraw.ImageDraw,
    text: str,
    max_width: int,
    max_lines: int,
    start: int,
    minimum: int,
    bold: bool = True,
) -> tuple[ImageFont.FreeTypeFont, list[str]]:
    size = start
    while size > minimum:
        font = _font(size, bold=bold)
        lines = _wrap(draw, text, font, max_width)
        if len(lines) <= max_lines:
            return font, lines
        size -= max(2, size // 14)
    font = _font(minimum, bold=bold)
    return font, _wrap(draw, text, font, max_width)[:max_lines]


def _tracked_text(
    draw: ImageDraw.ImageDraw,
    xy: tuple[int, int],
    text: str,
    font: ImageFont.FreeTypeFont,
    fill: tuple[int, int, int],
    tracking: float = 2.0,
) -> None:
    x, y = xy
    for char in text:
        draw.text((x, y), char, font=font, fill=fill)
        x += draw.textlength(char, font=font) + tracking


def _chip(
    draw: ImageDraw.ImageDraw,
    xy: tuple[int, int],
    text: str,
    font_size: int,
    fg: tuple[int, int, int],
    bg: tuple[int, int, int],
    border: tuple[int, int, int] | None = None,
    pad: int = 14,
) -> tuple[int, int]:
    font = _font(font_size, bold=True)
    text_width = draw.textlength(text, font=font)
    w = int(text_width + pad * 2)
    h = int(font_size + pad * 1.5)
    x, y = xy
    draw.rounded_rectangle([x, y, x + w, y + h], radius=h // 2, fill=bg,
                           outline=border, width=2 if border else 0)
    draw.text((x + pad, y + pad * 0.55), text, font=font, fill=fg)
    return w, h


def design_frame(
    out_path: str | Path,
    *,
    headline: str,
    kicker: str,
    body: str = "",
    palette: Sequence[str],
    width: int = 1080,
    height: int = 1920,
    variant: int = 0,
    style: str = "editorial",
    label: str = "",
    texture_source: str | Path | None = None,
) -> dict:
    """Compose one designed frame. Returns metadata about what was drawn."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    size = (width, height)
    colours = [hex_to_rgb(c) for c in palette][:4] or [hex_to_rgb("#0E1117"), hex_to_rgb("#F2F0EA"),
                                                       hex_to_rgb("#E4572E"), hex_to_rgb("#3A6EA5")]
    while len(colours) < 4:
        colours.append(colours[-1])

    roles = palette_roles(list(palette))
    base, ink = hex_to_rgb(roles["base"]), hex_to_rgb(roles["ink"])
    accent, second = hex_to_rgb(roles["accent"]), hex_to_rgb(roles["support"])
    # an accent that is too close to the ground disappears; lift it toward ink
    if abs(_luma(accent) - _luma(base)) < 0.20:
        accent = _mix(accent, ink, 0.62)
    rng = _seed(headline, kicker, variant, style)

    # --- ground: a mesh of blurred colour fields, not a flat gradient ------
    img = _vertical_gradient(size, base, _mix(base, second, 0.22))
    blobs = [
        (rng.uniform(0.05, 0.95), rng.uniform(0.05, 0.45), rng.uniform(0.35, 0.75), second, 0.55),
        (rng.uniform(0.05, 0.95), rng.uniform(0.35, 0.80), rng.uniform(0.30, 0.65), accent, 0.42),
        (rng.uniform(0.00, 1.00), rng.uniform(0.55, 1.00), rng.uniform(0.40, 0.80),
         _mix(base, ink, 0.35), 0.30),
        (rng.uniform(0.00, 1.00), rng.uniform(0.00, 0.30), rng.uniform(0.45, 0.85), accent, 0.20),
    ]
    for cx, cy, radius, colour, strength in blobs:
        layer = _radial_light(size, (cx, cy), radius, colour, strength)
        # screen keeps the light visible instead of letting it collapse to black
        from PIL import ImageChops

        img = ImageChops.screen(img, layer.point(lambda v: int(v * 0.55)))
        img = Image.blend(img, ImageChops.screen(img, layer), 0.22)

    # a soft directional sweep gives the mesh a light source
    sweep = Image.new("L", (max(8, width // 16), max(8, height // 16)), 0)
    sdraw = ImageDraw.Draw(sweep)
    angle_top = rng.uniform(0.0, 0.4)
    sdraw.polygon(
        [(0, 0), (sweep.width * (0.55 + angle_top), 0), (0, sweep.height * 0.8)],
        fill=90,
    )
    sweep = sweep.filter(ImageFilter.GaussianBlur(sweep.width / 6)).resize(
        (width, height), Image.Resampling.BICUBIC
    )
    img = Image.composite(Image.new("RGB", size, _mix(ink, base, 0.5)), img, sweep.point(lambda v: int(v * 0.5)))

    # --- optional real texture: the uploaded photograph, deeply treated ------
    if texture_source and Path(texture_source).exists():
        try:
            photo = Image.open(texture_source).convert("RGB")
            photo = _cover(photo, size)
            photo = ImageEnhance.Color(photo).enhance(0.35)
            photo = ImageOps_colorize(photo, ink, second)
            photo = photo.filter(ImageFilter.GaussianBlur(width / 140))
            img = Image.blend(img, photo, 0.62)
        except Exception:
            pass

    # --- geometric composition: quiet arcs / rules tied to the variant ------
    overlay = Image.new("RGBA", size, (0, 0, 0, 0))
    odraw = ImageDraw.Draw(overlay)
    if style in {"editorial", "cinematic"}:
        cx = int(width * rng.uniform(0.35, 0.75))
        cy = int(height * rng.uniform(0.30, 0.55))
        for i, radius in enumerate((width * 0.72, width * 0.52, width * 0.34)):
            alpha = int(28 - i * 6)
            odraw.ellipse(
                [cx - radius, cy - radius, cx + radius, cy + radius],
                outline=(*ink, max(8, alpha)),
                width=max(2, int(width / 420)),
            )
    elif style == "graphic":
        # a short vertical rule at the margin, never a full-bleed band across the type
        bar_h = int(height * 0.09)
        odraw.rectangle([int(width * 0.045), int(height * 0.30),
                         int(width * 0.045) + max(4, int(width / 240)), int(height * 0.30) + bar_h],
                        fill=(*accent, 120))
    # hero form: a soft sculptural object in the middle band, so the frame has
    # a subject instead of empty space. Variant-driven shape and placement.
    form = Image.new("RGBA", size, (0, 0, 0, 0))
    fdraw = ImageDraw.Draw(form)
    cx = int(width * (0.50 + (variant % 3 - 1) * 0.10))
    cy = int(height * 0.545)
    radius = int(width * (0.30 + (variant % 2) * 0.05))
    rim = Image.new("RGBA", size, (0, 0, 0, 0))
    rdraw = ImageDraw.Draw(rim)
    # two offset forms read as depth rather than as a placeholder rectangle
    box = [cx - radius, cy - radius, cx + radius, cy + radius]
    fdraw.ellipse(box, fill=(*second, 105))
    inner = int(radius * 0.62)
    fdraw.ellipse([cx - inner, cy - inner - int(radius * 0.10),
                   cx + inner, cy + inner - int(radius * 0.10)], fill=(*accent, 70))
    rdraw.arc(box, start=200 + variant * 26, end=345 + variant * 26,
              fill=(*accent, 190), width=max(3, int(width / 240)))
    rdraw.arc([cx - inner, cy - inner, cx + inner, cy + inner],
              start=20 + variant * 18, end=150 + variant * 18,
              fill=(*ink, 90), width=max(2, int(width / 360)))
    form = form.filter(ImageFilter.GaussianBlur(radius * 0.05))
    rim = rim.filter(ImageFilter.GaussianBlur(max(1, radius * 0.02)))
    overlay = Image.alpha_composite(Image.alpha_composite(overlay, form), rim)
    odraw = ImageDraw.Draw(overlay)

    # editorial corner ticks: a thin crop-mark frame that reads as "designed"
    tick = max(2, int(width / 360))
    arm = int(width * 0.055)
    pad = int(width * 0.045)
    for (x, y, dx, dy) in [
        (pad, pad, 1, 1),
        (width - pad, pad, -1, 1),
        (pad, height - pad, 1, -1),
        (width - pad, height - pad, -1, -1),
    ]:
        odraw.line([(x, y), (x + arm * dx, y)], fill=(*ink, 70), width=tick)
        odraw.line([(x, y), (x, y + arm * dy)], fill=(*ink, 70), width=tick)
    img = Image.alpha_composite(img.convert("RGBA"), overlay).convert("RGB")

    # --- typography --------------------------------------------------------
    # Layout contract with the caption layer: the design owns the top 55% of
    # the frame, the bottom 30% is reserved for burned captions. Nothing here
    # may cross below `caption_reserve`.
    draw = ImageDraw.Draw(img)
    margin = int(width * 0.085)
    safe_top = int(height * 0.10)
    caption_reserve = int(height * 0.58)
    ink_soft = _mix(ink, base, 0.30)

    if kicker:
        kicker_font = _font(max(18, int(width * 0.028)), bold=True)
        _tracked_text(draw, (margin, safe_top), kicker.upper()[:46], kicker_font, accent,
                      tracking=width * 0.0042)

    max_text_width = width - margin * 2
    head_font, lines = _fit_font(draw, headline, max_text_width, 3, int(width * 0.098),
                                 int(width * 0.044))
    line_height = int(head_font.size * 1.18)
    block_height = line_height * len(lines)

    if body:
        body_font = _font(max(19, int(width * 0.030)), bold=False)
        body_lines = _wrap(draw, body, body_font, max_text_width)[:2]
        body_height = int(body_font.size * 1.4) * len(body_lines)
    else:
        body_font, body_lines, body_height = None, [], 0

    total = block_height + (int(height * 0.022) + body_height if body_lines else 0)
    # anchor the block in the upper half, between the kicker and the reserve
    head_y = int(height * 0.27)
    head_y = min(head_y, caption_reserve - total - int(height * 0.04))
    head_y = max(safe_top + int(height * 0.09), head_y)

    # accent rule above the headline
    rule_y = head_y - int(height * 0.030)
    draw.rectangle([margin, rule_y, margin + int(width * 0.13), rule_y + max(4, int(height / 320))],
                   fill=accent)

    y = head_y
    for line in lines:
        draw.text((margin + 2, y + 3), line, font=head_font, fill=_mix(base, (0, 0, 0), 0.45))
        draw.text((margin, y), line, font=head_font, fill=ink)
        y += line_height

    if body_lines:
        y += int(height * 0.022)
        for line in body_lines:
            draw.text((margin, y), line, font=body_font, fill=ink_soft)
            y += int(body_font.size * 1.40)

    # --- provenance chip: top-right, clear of the caption band --------------
    if label:
        chip_font_size = max(15, int(width * 0.019))
        chip_w = int(draw.textlength(label.upper(), font=_font(chip_font_size, bold=True))
                     + chip_font_size * 2.0)
        _chip(
            draw,
            (width - margin - chip_w, safe_top - int(height * 0.008)),
            label.upper(),
            chip_font_size,
            fg=ink,
            bg=(0, 0, 0),
            border=_mix(ink, base, 0.55),
        )

    # --- finishing ---------------------------------------------------------
    img = ImageEnhance.Contrast(img).enhance(1.10)
    img = ImageEnhance.Color(img).enhance(1.06)
    img = _vignette(img, 0.32 if size[1] > size[0] else 0.24)
    img = _grain(img, 0.030, rng)
    img.save(out_path, quality=94, subsampling=1)

    return {
        "output": str(out_path),
        "width": width,
        "height": height,
        "headline": headline,
        "kicker": kicker,
        "palette": list(palette),
        "renderer": "studio.localfx.design_frame",
    }


def _photo_type_block(frame: Image.Image, name: str, kicker: str, index: int) -> Image.Image:
    """Editorial type that sits *with* the photograph, not on top of the subject.

    A scrim keeps the caption legible, but a bright frame needs more than a
    subtitle: the artwork carries a small kicker (the concept) at the top of the
    safe area and one tracked word (the treatment) in the mid-frame. The
    narrative line is the caption layer's job, so nothing is said twice.
    """
    width, height = frame.size
    draw = ImageDraw.Draw(frame)
    margin = int(width * 0.085)

    if kicker:
        from PIL import ImageStat

        probe = _font(max(14, int(width * 0.021)), bold=True)
        available = width - margin * 2
        natural = draw.textlength(kicker.upper(), font=probe)
        tracking = max(1.0, min(width * 0.0030, (available - natural) / max(1, len(kicker))))
        ky = int(height * 0.062)
        band = frame.crop((margin, ky - 2, width - margin, ky + int(probe.size * 1.4)))
        k_luma = ImageStat.Stat(band.convert("L")).mean[0] / 255
        k_ink = (20, 20, 22) if k_luma > 0.6 else (255, 255, 255)
        _tracked_text(draw, (margin, ky), kicker.upper(), probe, k_ink, tracking=tracking)

    if name:
        label = name.upper()
        word_font = _font(max(26, int(width * 0.058)), bold=True)
        natural = draw.textlength(label, font=word_font)
        available = width - margin * 2
        tracking = max(1.0, min(width * 0.012, (available - natural) / max(1, len(label))))
        # the word sits low in the frame with the caption scrim beneath it,
        # so the treatment reads as a title card rather than a stray label
        y = int(height * (0.735 + (index % 2) * 0.028))

        # measure the ground behind the word and pick ink that survives it,
        # rather than assuming white type works on every photograph
        word_h = int(word_font.size * 1.2)
        region = frame.crop((margin, y - 4, width - margin, y + word_h))
        # darken only the measured band, so light ink always has a ground
        band = Image.new("RGBA", region.size, (0, 0, 0, 0))
        from PIL import ImageDraw as _ID

        _ID.Draw(band).rectangle([0, 0, region.size[0], region.size[1]], fill=(0, 0, 0, 0))
        scrim = Image.new("RGBA", frame.size, (0, 0, 0, 0))
        _ID.Draw(scrim).rectangle(
            [0, y - int(height * 0.018), width, y + word_h + int(height * 0.012)],
            fill=(0, 0, 0, 96),
        )
        frame = Image.alpha_composite(frame.convert("RGBA"), scrim).convert("RGB")
        draw = ImageDraw.Draw(frame)
        region = frame.crop((margin, y - 4, width - margin, y + word_h))
        from PIL import ImageStat

        luma = ImageStat.Stat(region.convert("L")).mean[0] / 255
        ink = (18, 18, 20) if luma > 0.72 else (250, 250, 248)
        shadow = (255, 255, 255) if luma > 0.72 else (0, 0, 0)

        x = margin
        for char in label:
            draw.text((x + 2, y + 2), char, font=word_font, fill=shadow)
            draw.text((x, y), char, font=word_font, fill=ink)
            x += draw.textlength(char, font=word_font) + tracking
    return frame


def _mix(a: tuple[int, int, int], b: tuple[int, int, int], t: float) -> tuple[int, int, int]:
    t = max(0.0, min(1.0, t))
    return (int(a[0] + (b[0] - a[0]) * t),
            int(a[1] + (b[1] - a[1]) * t),
            int(a[2] + (b[2] - a[2]) * t))


def ImageOps_colorize(img: Image.Image, dark: tuple[int, int, int], light: tuple[int, int, int]) -> Image.Image:
    """Duotone map: luminance -> palette ramp."""
    grey = img.convert("L")
    return Image.merge(
        "RGB",
        (
            grey.point(lambda v, d=dark[0], l=light[0]: int(d + (l - d) * v / 255)),
            grey.point(lambda v, d=dark[1], l=light[1]: int(d + (l - d) * v / 255)),
            grey.point(lambda v, d=dark[2], l=light[2]: int(d + (l - d) * v / 255)),
        ),
    )


def _cover(img: Image.Image, size: tuple[int, int]) -> Image.Image:
    target_w, target_h = size
    ratio = max(target_w / img.width, target_h / img.height)
    resized = img.resize((max(1, int(img.width * ratio)), max(1, int(img.height * ratio))),
                         Image.Resampling.LANCZOS)
    left = (resized.width - target_w) // 2
    top = (resized.height - target_h) // 2
    return resized.crop((left, top, left + target_w, top + target_h))


