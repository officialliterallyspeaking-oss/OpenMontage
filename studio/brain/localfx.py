"""Deterministic local art direction — used only when no model provider is configured.

This module is not a stub that draws grey boxes. It composes a real editorial
frame: layered gradient fields, palette-driven light, film grain, vignette,
typographic hierarchy and safe-area aware placement. It is genuinely designed
output — it is simply *designed by rules*, not generated by a model, and every
asset it produces is stamped ``provenance: "local"`` so the UI, the QA report and
the publishing package all state that plainly.

Why have it at all? Because the pipeline is real: script, storyboard, timing,
motion, captions, QA and the publishing package are all genuine whether or not an
image model is reachable. The honest thing is to run the whole machine and label
the one stage that had to be local, rather than pretend the machine needs a model
to work.
"""

from __future__ import annotations

import hashlib
import math
import random
from pathlib import Path
from typing import Iterable, Sequence

from PIL import Image, ImageChops, ImageDraw, ImageEnhance, ImageFilter, ImageFont

FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    "/usr/share/fonts/truetype/freefont/FreeSansBold.ttf",
]


def _font(size: int, bold: bool = True) -> ImageFont.FreeTypeFont:
    for path in FONT_CANDIDATES:
        if Path(path).exists() and ("Bold" in path) == bold:
            try:
                return ImageFont.truetype(path, size)
            except Exception:
                continue
    for path in FONT_CANDIDATES:
        if Path(path).exists():
            try:
                return ImageFont.truetype(path, size)
            except Exception:
                continue
    return ImageFont.load_default()


def hex_to_rgb(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    if len(value) == 3:
        value = "".join(c * 2 for c in value)
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def _luma(rgb: tuple[int, int, int]) -> float:
    return (0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]) / 255


def _saturation(rgb: tuple[int, int, int]) -> float:
    high, low = max(rgb), min(rgb)
    return 0.0 if high == 0 else (high - low) / high


def palette_roles(palette: Sequence[str]) -> dict[str, str]:
    """Assign base / ink / accent / support by measuring, not by position.

    User palettes, niche palettes and colours sampled from a photograph all
    arrive in arbitrary order. Text has to land on the brightest one and the
    most saturated has to become the accent, or you get green body copy.
    """
    colours = [c for c in palette if c] or ["#0E1117", "#F2F0EA", "#E4572E"]
    rgb = [(c, hex_to_rgb(c)) for c in colours]
    base = min(rgb, key=lambda item: _luma(item[1]))[0]
    remaining = [item for item in rgb if item[0] != base] or rgb
    ink = max(remaining, key=lambda item: _luma(item[1]))[0]
    rest = [item for item in remaining if item[0] != ink] or remaining
    accent = max(rest, key=lambda item: _saturation(item[1]))[0]
    rest = [item for item in rest if item[0] != accent] or rest
    support = rest[0][0] if rest else accent
    return {"base": base, "ink": ink, "accent": accent, "support": support}


def _seed(*parts: object) -> random.Random:
    digest = hashlib.sha256("|".join(str(p) for p in parts).encode()).hexdigest()
    return random.Random(int(digest[:16], 16))


def _vertical_gradient(size: tuple[int, int], top: tuple[int, int, int], bottom: tuple[int, int, int]) -> Image.Image:
    width, height = size
    column = Image.new("RGB", (1, height))
    px = column.load()
    for y in range(height):
        t = y / max(1, height - 1)
        # smoothstep for a softer ramp
        t = t * t * (3 - 2 * t)
        px[0, y] = (
            int(top[0] + (bottom[0] - top[0]) * t),
            int(top[1] + (bottom[1] - top[1]) * t),
            int(top[2] + (bottom[2] - top[2]) * t),
        )
    return column.resize((width, height), Image.Resampling.BICUBIC)


def _radial_light(
    size: tuple[int, int],
    center: tuple[float, float],
    radius: float,
    colour: tuple[int, int, int],
    strength: float = 0.55,
) -> Image.Image:
    """A soft light pool, painted small then upscaled (fast + smooth)."""
    width, height = size
    scale = 8
    small = (max(8, width // scale), max(8, height // scale))
    layer = Image.new("L", small, 0)
    draw = ImageDraw.Draw(layer)
    cx, cy = center[0] * small[0], center[1] * small[1]
    r = radius * min(small)
    draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=int(255 * strength))
    layer = layer.filter(ImageFilter.GaussianBlur(radius=max(1, r / 2)))
    layer = layer.resize((width, height), Image.Resampling.BICUBIC)
    tint = Image.new("RGB", (width, height), colour)
    return Image.composite(tint, Image.new("RGB", size, (0, 0, 0)), layer)


def _grain(img: Image.Image, amount: float = 0.055, seed: random.Random | None = None) -> Image.Image:
    rng = seed or random.Random(7)
    width, height = img.size
    noise = Image.new("L", (width, height))
    px = noise.load()
    for y in range(0, height):
        for x in range(0, width):
            px[x, y] = int(128 + (rng.random() - 0.5) * 255 * amount * 4)
    noise = noise.filter(ImageFilter.GaussianBlur(0.4))
    return Image.blend(img, Image.merge("RGB", (noise, noise, noise)), amount)


def _vignette(img: Image.Image, strength: float = 0.35) -> Image.Image:
    width, height = img.size
    small = (max(8, width // 12), max(8, height // 12))
    mask = Image.new("L", small, 0)
    draw = ImageDraw.Draw(mask)
    pad = -min(small) * 0.15
    draw.ellipse([pad, pad, small[0] - pad, small[1] - pad], fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(min(small) / 6)).resize(
        (width, height), Image.Resampling.BICUBIC
    )
    dark = Image.new("RGB", (width, height), (0, 0, 0))
    blended = Image.composite(img, dark, mask)
    return Image.blend(img, blended, strength)


def _wrap(draw: ImageDraw.ImageDraw, text: str, font: ImageFont.FreeTypeFont, max_width: int) -> list[str]:
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        trial = f"{current} {word}".strip()
        if draw.textlength(trial, font=font) <= max_width or not current:
            current = trial
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def _fit_font(
    draw: ImageDraw.ImageDraw,
    text: str,
    max_width: int,
    max_lines: int,
    start: int,
    minimum: int,
    bold: bool = True,
) -> tuple[ImageFont.FreeTypeFont, list[str]]:
    size = start
    while size > minimum:
        font = _font(size, bold=bold)
        lines = _wrap(draw, text, font, max_width)
        if len(lines) <= max_lines:
            return font, lines
        size -= max(2, size // 14)
    font = _font(minimum, bold=bold)
    return font, _wrap(draw, text, font, max_width)[:max_lines]


def _fit_with(
    draw: ImageDraw.ImageDraw,
    text: str,
    make_font,
    max_width: int,
    max_lines: int,
    start: int,
    minimum: int,
) -> tuple[ImageFont.FreeTypeFont, list[str]]:
    """Fit text to a line budget using any font factory (serif, ui, fallback)."""
    size = start
    while size > minimum:
        font = make_font(size)
        lines = _wrap(draw, text, font, max_width)
        if len(lines) <= max_lines:
            return font, lines
        size -= max(2, size // 16)
    font = make_font(minimum)
    return font, _wrap(draw, text, font, max_width)[:max_lines]



def _tracked_text(
    draw: ImageDraw.ImageDraw,
    xy: tuple[int, int],
    text: str,
    font: ImageFont.FreeTypeFont,
    fill: tuple[int, int, int],
    tracking: float = 2.0,
) -> None:
    x, y = xy
    for char in text:
        draw.text((x, y), char, font=font, fill=fill)
        x += draw.textlength(char, font=font) + tracking


def _chip(
    draw: ImageDraw.ImageDraw,
    xy: tuple[int, int],
    text: str,
    font_size: int,
    fg: tuple[int, int, int],
    bg: tuple[int, int, int],
    border: tuple[int, int, int] | None = None,
    pad: int = 14,
) -> tuple[int, int]:
    font = _font(font_size, bold=True)
    text_width = draw.textlength(text, font=font)
    w = int(text_width + pad * 2)
    h = int(font_size + pad * 1.5)
    x, y = xy
    draw.rounded_rectangle([x, y, x + w, y + h], radius=h // 2, fill=bg,
                           outline=border, width=2 if border else 0)
    draw.text((x + pad, y + pad * 0.55), text, font=font, fill=fg)
    return w, h


# ── type, shared with the interface ────────────────────────────────────
# The frames are rendered server-side, so they cannot use the woff2 files
# the browser loads. `studio/assets/fonts/` holds TTF builds of the same
# two families (Instrument Serif + Inter) so a composed frame and the app
# around it are visibly the same product.

FONT_DIR = Path(__file__).resolve().parent.parent / "assets" / "fonts"


def _font_file(name: str) -> str | None:
    candidate = FONT_DIR / name
    return str(candidate) if candidate.exists() else None


def _display_font(size: int) -> ImageFont.FreeTypeFont:
    """The headline face: a high-contrast serif, or the best local fallback."""
    for name in ("instrument-serif-400.ttf",):
        path = _font_file(name)
        if path:
            try:
                return ImageFont.truetype(path, size)
            except Exception:
                pass
    return _font(size, bold=True)


def _ui_font(size: int, weight: int = 400) -> ImageFont.FreeTypeFont:
    for name in (f"inter-{weight}.ttf", "inter-400.ttf"):
        path = _font_file(name)
        if path:
            try:
                return ImageFont.truetype(path, size)
            except Exception:
                pass
    return _font(size, bold=weight >= 600)


# ── composition primitives ────────────────────────────────────────────

def _hairline(draw: ImageDraw.ImageDraw, points, fill, width: int = 1) -> None:
    draw.line(points, fill=fill, width=width)


def _soft_disc(size, centre, radius: float, colour, strength: float) -> Image.Image:
    """A soft light disc, rendered at low resolution then scaled up."""
    return _radial_light(size, centre, radius, colour, strength)


def _composition_aperture(size, ink, accent, second, base, rng):
    """A field of light with a hard-edged disc cut into it: a lens, a sun."""
    w, h = size
    layer = Image.new("RGBA", size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    cx, cy = int(w * 0.60), int(h * 0.375)
    r = int(w * 0.30)
    disc = Image.new("RGBA", size, (0, 0, 0, 0))
    dd = ImageDraw.Draw(disc)
    dd.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(*accent, 255))
    # inside the disc only: a darker lower band, so it reads as a printed
    # object catching light rather than as a rectangle on the page
    band = Image.new("RGBA", size, (0, 0, 0, 0))
    bd = ImageDraw.Draw(band)
    bd.rectangle([cx - r, cy + int(r * 0.72), cx + r, cy + r],
                 fill=(*_mix(accent, base, 0.30), 255))
    # paint the band inside the disc only: mask = band alpha AND disc alpha
    mask = ImageChops.multiply(band.split()[3], disc.split()[3])
    disc.paste(band, (0, 0), mask)
    layer.alpha_composite(disc)
    for i, frac in enumerate((0.52, 0.40, 0.28)):
        rr = int(w * frac)
        d.arc([cx - rr, cy - rr, cx + rr, cy + rr],
              start=-150, end=72, fill=(*ink, 96 - i * 22), width=max(2, int(w / 700)))
    return layer


def _composition_column(size, ink, accent, second, base, rng):
    """A committed vertical band of colour, cut by a light disc."""
    w, h = size
    layer = Image.new("RGBA", size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    x0, x1 = int(w * 0.50), int(w * 0.92)
    top, bottom = int(h * 0.16), int(h * 0.545)
    d.rectangle([x0, top, x1, bottom], fill=(*second, 225))
    d.rectangle([x0, top, x1, int(top + (bottom - top) * 0.07)], fill=(*accent, 255))
    cx, cy, r = int(w * 0.71), int(h * 0.40), int(w * 0.185)
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(*ink, 255))
    d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=(*accent, 255), width=max(2, int(w / 460)))
    # a measure scale: five ticks, printerly
    for i in range(5):
        y = int(h * (0.20 + i * 0.05))
        d.line([(int(w * 0.085), y), (int(w * 0.085) + int(w * 0.022), y)],
               fill=(*ink, 120), width=max(1, int(w / 900)))
    return layer


def _composition_horizon(size, ink, accent, second, base, rng):
    """Landscape logic: a luminous band, a horizon, a sun sitting on it."""
    w, h = size
    layer = Image.new("RGBA", size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    horizon = int(h * 0.455)
    r = int(w * 0.20)
    cx = int(w * 0.60)
    # the sun sits on the line, its lower arc clipped by the ground plane
    d.ellipse([cx - r, horizon - 2 * r, cx + r, horizon], fill=(*ink, 255))
    d.rectangle([0, horizon, w, horizon + int(h * 0.010)], fill=(*accent, 255))
    ground = Image.new("RGBA", size, (0, 0, 0, 0))
    gd = ImageDraw.Draw(ground)
    gd.rectangle([0, horizon + int(h * 0.010), w, int(h * 0.545)],
                 fill=(*_mix(second, base, 0.20), 150))
    ground = ground.filter(ImageFilter.GaussianBlur(w / 90))
    layer.alpha_composite(ground)
    return layer


def _composition_plates(size, ink, accent, second, base, rng):
    """Offset plates: a printed object, seen flat, stacked in space."""
    w, h = size
    layer = Image.new("RGBA", size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    bw, bh = int(w * 0.52), int(h * 0.30)
    x0, y0 = int(w * 0.30), int(h * 0.13)
    step = int(w * 0.065)
    d.rounded_rectangle([x0, y0, x0 + bw, y0 + bh], radius=int(w * 0.01),
                        fill=(*second, 235))
    d.rounded_rectangle([x0 + step, y0 + step, x0 + bw + step, y0 + bh + step],
                        radius=int(w * 0.01), fill=(*accent, 255))
    d.rounded_rectangle([x0 + step * 2, y0 + step * 2, x0 + bw + step * 2, y0 + bh + step * 2],
                        radius=int(w * 0.01), fill=(*ink, 255))
    d.rectangle([x0 + step * 2, y0 + bh + step * 2 - int(h * 0.026),
                 x0 + step * 2 + int(w * 0.14), y0 + bh + step * 2], fill=(*accent, 255))
    return layer


def _composition_field(size, ink, accent, second, base, rng):
    """Typographic field: a ghost glyph, a hard bar, one dot of accent."""
    w, h = size
    layer = Image.new("RGBA", size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    ghost = _display_font(int(w * 0.70))
    d.text((int(w * 0.34), int(h * 0.085)), "M", font=ghost, fill=(*ink, 34))
    d.rectangle([0, int(h * 0.44), int(w * 0.40), int(h * 0.455)], fill=(*accent, 255))
    d.ellipse([int(w * 0.72), int(h * 0.20), int(w * 0.72) + int(w * 0.05),
               int(h * 0.20) + int(w * 0.05)], fill=(*accent, 255))
    return layer


COMPOSITIONS = (_composition_aperture, _composition_column,
                _composition_horizon, _composition_plates, _composition_field)

def design_frame(
    out_path: str | Path,
    *,
    headline: str,
    kicker: str,
    body: str = "",
    palette: Sequence[str],
    width: int = 1080,
    height: int = 1920,
    variant: int = 0,
    style: str = "editorial",
    label: str = "",
    texture_source: str | Path | None = None,
) -> dict:
    """Compose one designed frame. Returns metadata about what was drawn."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    size = (width, height)
    colours = [hex_to_rgb(c) for c in palette][:4] or [hex_to_rgb("#0E1117"), hex_to_rgb("#F2F0EA"),
                                                       hex_to_rgb("#E4572E"), hex_to_rgb("#3A6EA5")]
    while len(colours) < 4:
        colours.append(colours[-1])

    roles = palette_roles(list(palette))
    base, ink = hex_to_rgb(roles["base"]), hex_to_rgb(roles["ink"])
    accent, second = hex_to_rgb(roles["accent"]), hex_to_rgb(roles["support"])
    # an accent that is too close to the ground disappears; lift it toward ink
    if abs(_luma(accent) - _luma(base)) < 0.20:
        accent = _mix(accent, ink, 0.62)
    rng = _seed(headline, kicker, variant, style)

    # --- ground: a decisive dark field --------------------------------------
    # Posters work because the ground is committed to one value. Everything
    # else in the frame is then either light or accent, never mush.
    deep = _mix(base, (0, 0, 0), 0.55)
    img = _vertical_gradient(size, deep, _mix(base, second, 0.16))
    # one broad wash of the support colour high in the frame, then the accent
    # low and off-axis. Two lights, clearly placed, read as a photograph.
    for cx, cy, radius, colour, strength in [
        (0.68, 0.16, 0.85, second, 0.42),
        (0.22, 0.86, 0.80, accent, 0.30),
    ]:
        layer = _radial_light(size, (cx, cy), radius, colour, strength)
        img = Image.composite(ImageChops.screen(img, layer), img,
                              layer.convert("L").point(lambda v: int(v * 0.75)))

    # a soft directional sweep gives the mesh a light source
    sweep = Image.new("L", (max(8, width // 16), max(8, height // 16)), 0)
    sdraw = ImageDraw.Draw(sweep)
    angle_top = rng.uniform(0.0, 0.4)
    sdraw.polygon(
        [(0, 0), (sweep.width * (0.55 + angle_top), 0), (0, sweep.height * 0.8)],
        fill=90,
    )
    sweep = sweep.filter(ImageFilter.GaussianBlur(sweep.width / 6)).resize(
        (width, height), Image.Resampling.BICUBIC
    )
    img = Image.composite(Image.new("RGB", size, _mix(ink, base, 0.5)), img, sweep.point(lambda v: int(v * 0.5)))

    # --- optional real texture: the uploaded photograph, deeply treated ------
    if texture_source and Path(texture_source).exists():
        try:
            photo = Image.open(texture_source).convert("RGB")
            photo = _cover(photo, size)
            photo = ImageEnhance.Color(photo).enhance(0.35)
            photo = ImageOps_colorize(photo, ink, second)
            photo = photo.filter(ImageFilter.GaussianBlur(width / 140))
            img = Image.blend(img, photo, 0.62)
        except Exception:
            pass

    # --- composition: a layered still life, not a smudge -------------------
    # Every frame is built in three planes: a defocused backplate that gives
    # depth, a crisp middle plane that carries the geometry, and type on top.
    # The variant chooses the composition, so four shots read as four ideas
    # rather than four rearrangements of the same blob.
    composition = COMPOSITIONS[variant % len(COMPOSITIONS)]
    mid = composition(size, ink, accent, second, base, rng)

    # a defocused echo behind the crisp plane gives depth without haze
    echo = mid.filter(ImageFilter.GaussianBlur(int(width * 0.018)))
    er, eg, eb, ea = echo.split()
    echo = Image.merge("RGBA", (er, eg, eb, ea.point(lambda v: int(v * 0.34))))

    img = Image.alpha_composite(img.convert("RGBA"), echo)
    img = Image.alpha_composite(img, mid)

    # a single directional light from one corner, very soft
    leak = Image.new("RGBA", size, (0, 0, 0, 0))
    ld = ImageDraw.Draw(leak)
    lx = int(width * rng.uniform(0.05, 0.95))
    ld.ellipse([lx - int(width * 0.9), -int(height * 0.35),
                lx + int(width * 0.9), int(height * 0.42)],
               fill=(*_mix(ink, accent, 0.35), 26))
    img = Image.alpha_composite(img, leak.filter(ImageFilter.GaussianBlur(width / 9)))

    # --- optional real texture: the uploaded photograph, deeply treated ------
    if texture_source and Path(texture_source).exists():
        try:
            photo = Image.open(texture_source).convert("RGB")
            photo = _cover(photo, size)
            photo = ImageEnhance.Color(photo).enhance(0.55)
            photo = ImageOps_colorize(photo, ink, second)
            photo = photo.filter(ImageFilter.GaussianBlur(width / 260))
            # keep the photograph readable: it is the subject, not a wash
            treated = Image.new("RGBA", size, (0, 0, 0, 0))
            treated.paste(photo, (0, 0))
            treated.putalpha(Image.new("L", size, 196))
            img = Image.alpha_composite(img, treated)
        except Exception:
            pass

    # the caption stage (roughly 60-79% of the height) gets a soft well so
    # burned captions always have a quiet ground to sit on
    well = Image.new("RGBA", size, (0, 0, 0, 0))
    wd = ImageDraw.Draw(well)
    wd.rectangle([0, int(height * 0.575), width, int(height * 0.815)], fill=(*deep, 110))
    well = well.filter(ImageFilter.GaussianBlur(width / 26))
    img = Image.alpha_composite(img, well)

    # editorial crop marks: a thin corner frame that reads as "designed"
    marks = Image.new("RGBA", size, (0, 0, 0, 0))
    md = ImageDraw.Draw(marks)
    tick = max(2, int(width / 420))
    arm = int(width * 0.045)
    pad = int(width * 0.045)
    for (x, y, dx, dy) in [
        (pad, pad, 1, 1),
        (width - pad, pad, -1, 1),
        (width - pad, height - pad, -1, -1),
        (pad, height - pad, 1, -1),
    ]:
        md.line([(x, y), (x + arm * dx, y)], fill=(*ink, 56), width=tick)
        md.line([(x, y), (x, y + arm * dy)], fill=(*ink, 56), width=tick)
    img = Image.alpha_composite(img, marks)

    # a plate of shade under the type, so the serif never fights the artwork
    # the type needs a quiet ground, but only under itself: a soft dark
    # column behind the text block, feathered at the edges, leaving the top
    # of the frame and the caption stage untouched.
    scrim = Image.new("RGBA", size, (0, 0, 0, 0))
    sd = ImageDraw.Draw(scrim)
    sd.rectangle([0, int(height * 0.20), int(width * 0.94), int(height * 0.585)],
                 fill=(*deep, 132))
    scrim = scrim.filter(ImageFilter.GaussianBlur(width / 18))
    img = Image.alpha_composite(img, scrim)

    # --- typography ---------------------------------------------------------
    # Layout contract with the caption layer: the design owns the top 58% of
    # the frame, the remainder is reserved for burned captions. Nothing here
    # may cross below `caption_reserve`.
    draw = ImageDraw.Draw(img)
    margin = int(width * 0.085)
    safe_top = int(height * 0.10)
    caption_reserve = int(height * 0.58)
    strip_y = int(height * 0.545)
    ink_soft = _mix(ink, base, 0.26)
    max_text_width = width - margin * 2

    # kicker: a small square of accent, then tracked caps
    if kicker:
        kf = _ui_font(max(16, int(width * 0.0205)), 600)
        ky = safe_top - int(height * 0.004)
        square = max(3, int(width * 0.007))
        draw.rectangle([margin, ky + int(kf.size * 0.42),
                        margin + square, ky + int(kf.size * 0.42) + square], fill=accent)
        _tracked_text(draw, (margin + int(width * 0.026), ky), kicker.upper()[:44], kf,
                      _mix(ink, base, 0.12), tracking=width * 0.0052)

    # headline: the serif is the voice of the frame
    head_font, lines = _fit_with(
        draw, headline, _display_font, max_text_width, 3,
        int(width * 0.128), int(width * 0.052),
    )
    line_height = int(head_font.size * 1.06)
    block_height = line_height * len(lines)

    body_font, body_lines = None, []
    if body:
        body_font = _ui_font(max(19, int(width * 0.0275)), 400)
        body_lines = _wrap(draw, body, body_font, int(max_text_width * 0.94))[:2]
    body_height = int(body_font.size * 1.55) * len(body_lines) if body_lines else 0

    gap = int(height * 0.026) if body_lines else 0
    strip_pad = int(height * 0.011)
    total = block_height + (gap + body_height if body_lines else 0)
    head_y = strip_y - strip_pad - total
    head_y = max(head_y, safe_top + int(height * 0.085))

    # accent rule above the headline
    rule_y = head_y - int(height * 0.028)
    draw.rectangle([margin, rule_y, margin + int(width * 0.11),
                    rule_y + max(3, int(height / 420))], fill=accent)

    y = head_y
    for line in lines:
        draw.text((margin + 2, y + 3), line, font=head_font, fill=_mix(deep, (0, 0, 0), 0.55))
        draw.text((margin, y), line, font=head_font, fill=ink)
        y += line_height

    if body_lines:
        y += gap
        for line in body_lines:
            draw.text((margin, y), line, font=body_font, fill=ink_soft)
            y += int(body_font.size * 1.55)

    # data strip: the frame names itself, like a contact sheet
    strip_font = _ui_font(max(14, int(width * 0.0165)), 500)
    draw.line([(margin, strip_y), (width - margin, strip_y)],
              fill=(*ink, 52), width=max(1, int(width / 1000)))
    draw.text((margin, strip_y + strip_pad), f"FRAME {variant + 1:02d}",
              font=strip_font, fill=_mix(ink, base, 0.44))
    right = "LOCAL COMPOSITION"
    rw = draw.textlength(right, font=strip_font) + len(right) * (width * 0.0032)
    _tracked_text(draw, (width - margin - int(rw), strip_y + strip_pad), right,
                  strip_font, _mix(ink, base, 0.44), tracking=width * 0.0032)

    # --- footer: the frame signs itself, below where captions land ----------
    foot = Image.new("RGBA", size, (0, 0, 0, 0))
    fd2 = ImageDraw.Draw(foot)
    fy = int(height * 0.865)
    fd2.line([(margin, fy), (width - margin, fy)], fill=(*ink, 30), width=max(1, int(width / 1200)))
    ff = _ui_font(max(12, int(width * 0.0145)), 500)
    _tracked_text(fd2, (margin, fy + int(height * 0.012)), "OPENMONTAGE STUDIO",
                  ff, _mix(ink, base, 0.55), tracking=width * 0.0045)
    right_txt = f"{width}×{height}"
    rw2 = fd2.textlength(right_txt, font=ff)
    fd2.text((width - margin - rw2, fy + int(height * 0.012)), right_txt, font=ff,
             fill=_mix(ink, base, 0.55))
    # one accent tick, bottom-left, so the footer has a pulse
    fd2.rectangle([margin, fy - int(height * 0.007), margin + int(width * 0.018),
                   fy - int(height * 0.007) + max(2, int(height / 700))], fill=(*accent, 230))
    img = Image.alpha_composite(img, foot)

    # --- provenance chip: top-right, clear of the caption band --------------
    if label:
        chip_font_size = max(15, int(width * 0.019))
        chip_w = int(draw.textlength(label.upper(), font=_font(chip_font_size, bold=True))
                     + chip_font_size * 2.0)
        _chip(
            draw,
            (width - margin - chip_w, safe_top - int(height * 0.008)),
            label.upper(),
            chip_font_size,
            fg=ink,
            bg=(0, 0, 0),
            border=_mix(ink, base, 0.55),
        )

    # --- finishing ---------------------------------------------------------
    img = img.convert("RGB")
    img = ImageEnhance.Contrast(img).enhance(1.08)
    img = ImageEnhance.Color(img).enhance(1.04)
    bloom = img.filter(ImageFilter.GaussianBlur(max(6, int(width * 0.022))))
    img = ImageChops.screen(img, bloom.point(lambda v: int(v * 0.20)))
    img = _vignette(img, 0.30 if size[1] > size[0] else 0.22)
    img = _grain(img, 0.030, rng)
    img.save(out_path, quality=94, subsampling=1)

    return {
        "output": str(out_path),
        "width": width,
        "height": height,
        "headline": headline,
        "kicker": kicker,
        "palette": list(palette),
        "renderer": "studio.localfx.design_frame",
    }


def _photo_type_block(frame: Image.Image, name: str, kicker: str, index: int) -> Image.Image:
    """Editorial type that sits *with* the photograph, not on top of the subject.

    A scrim keeps the caption legible, but a bright frame needs more than a
    subtitle: the artwork carries a small kicker (the concept) at the top of the
    safe area and one tracked word (the treatment) in the mid-frame. The
    narrative line is the caption layer's job, so nothing is said twice.
    """
    width, height = frame.size
    draw = ImageDraw.Draw(frame)
    margin = int(width * 0.085)

    if kicker:
        from PIL import ImageStat

        probe = _font(max(14, int(width * 0.021)), bold=True)
        available = width - margin * 2
        natural = draw.textlength(kicker.upper(), font=probe)
        tracking = max(1.0, min(width * 0.0030, (available - natural) / max(1, len(kicker))))
        ky = int(height * 0.062)
        band = frame.crop((margin, ky - 2, width - margin, ky + int(probe.size * 1.4)))
        k_luma = ImageStat.Stat(band.convert("L")).mean[0] / 255
        k_ink = (20, 20, 22) if k_luma > 0.6 else (255, 255, 255)
        _tracked_text(draw, (margin, ky), kicker.upper(), probe, k_ink, tracking=tracking)

    if name:
        label = name.upper()
        word_font = _font(max(26, int(width * 0.058)), bold=True)
        natural = draw.textlength(label, font=word_font)
        available = width - margin * 2
        tracking = max(1.0, min(width * 0.012, (available - natural) / max(1, len(label))))
        # the word sits low in the frame with the caption scrim beneath it,
        # so the treatment reads as a title card rather than a stray label
        y = int(height * (0.735 + (index % 2) * 0.028))

        # measure the ground behind the word and pick ink that survives it,
        # rather than assuming white type works on every photograph
        word_h = int(word_font.size * 1.2)
        region = frame.crop((margin, y - 4, width - margin, y + word_h))
        # darken only the measured band, so light ink always has a ground
        band = Image.new("RGBA", region.size, (0, 0, 0, 0))
        from PIL import ImageDraw as _ID

        _ID.Draw(band).rectangle([0, 0, region.size[0], region.size[1]], fill=(0, 0, 0, 0))
        scrim = Image.new("RGBA", frame.size, (0, 0, 0, 0))
        _ID.Draw(scrim).rectangle(
            [0, y - int(height * 0.018), width, y + word_h + int(height * 0.012)],
            fill=(0, 0, 0, 96),
        )
        frame = Image.alpha_composite(frame.convert("RGBA"), scrim).convert("RGB")
        draw = ImageDraw.Draw(frame)
        region = frame.crop((margin, y - 4, width - margin, y + word_h))
        from PIL import ImageStat

        luma = ImageStat.Stat(region.convert("L")).mean[0] / 255
        ink = (18, 18, 20) if luma > 0.72 else (250, 250, 248)
        shadow = (255, 255, 255) if luma > 0.72 else (0, 0, 0)

        x = margin
        for char in label:
            draw.text((x + 2, y + 2), char, font=word_font, fill=shadow)
            draw.text((x, y), char, font=word_font, fill=ink)
            x += draw.textlength(char, font=word_font) + tracking
    return frame


def _mix(a: tuple[int, int, int], b: tuple[int, int, int], t: float) -> tuple[int, int, int]:
    t = max(0.0, min(1.0, t))
    return (int(a[0] + (b[0] - a[0]) * t),
            int(a[1] + (b[1] - a[1]) * t),
            int(a[2] + (b[2] - a[2]) * t))


def ImageOps_colorize(img: Image.Image, dark: tuple[int, int, int], light: tuple[int, int, int]) -> Image.Image:
    """Duotone map: luminance -> palette ramp."""
    grey = img.convert("L")
    return Image.merge(
        "RGB",
        (
            grey.point(lambda v, d=dark[0], l=light[0]: int(d + (l - d) * v / 255)),
            grey.point(lambda v, d=dark[1], l=light[1]: int(d + (l - d) * v / 255)),
            grey.point(lambda v, d=dark[2], l=light[2]: int(d + (l - d) * v / 255)),
        ),
    )


def _cover(img: Image.Image, size: tuple[int, int]) -> Image.Image:
    target_w, target_h = size
    ratio = max(target_w / img.width, target_h / img.height)
    resized = img.resize((max(1, int(img.width * ratio)), max(1, int(img.height * ratio))),
                         Image.Resampling.LANCZOS)
    left = (resized.width - target_w) // 2
    top = (resized.height - target_h) // 2
    return resized.crop((left, top, left + target_w, top + target_h))


# ---------------------------------------------------------------------------
# treatments of a real (uploaded) photograph
# ---------------------------------------------------------------------------

def photography_variants(
    source: str | Path,
    out_dir: str | Path,
    *,
    palette: Sequence[str],
    width: int = 1080,
    height: int = 1920,
    count: int = 4,
    narrate: str = "",
    focus: tuple[float, float] = (0.5, 0.45),
) -> list[dict]:
    """Real, derived frames from the user's own image.

    These are honest assets: crops and grades of a photograph the user supplied,
    not generated content. Provenance is recorded as ``source``.
    """
    source = Path(source)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    base = Image.open(source).convert("RGB")
    roles = palette_roles(list(palette))
    dark, light = hex_to_rgb(roles["base"]), hex_to_rgb(roles["ink"])
    accent = hex_to_rgb(roles["accent"])

    recipes = [
        ("wide", 1.0, 0.0, 1.02),
        ("detail", 1.55, 0.30, 1.0),
        ("macro", 2.30, 0.55, 1.0),
        ("air", 1.18, 0.12, 1.06),
        ("texture", 1.90, 0.80, 0.96),
    ]
    out: list[dict] = []
    for index in range(min(count, len(recipes))):
        name, zoom, bias, exposure = recipes[index]
        frame = _cover(base, (width, height))
        if zoom != 1.0:
            crop_w = int(width / zoom)
            crop_h = int(height / zoom)
            # centre the tighter crops on the measured focal point, nudged per
            # treatment so the four frames do not all land on the same detail
            cx = int(width * focus[0])
            cy = int(height * (focus[1] + (bias - 0.4) * 0.30))
            left = max(0, min(width - crop_w, cx - crop_w // 2))
            top = max(0, min(height - crop_h, cy - crop_h // 2))
            frame = frame.crop((left, top, left + crop_w, top + crop_h)).resize(
                (width, height), Image.Resampling.LANCZOS
            )
        frame = ImageEnhance.Brightness(frame).enhance(exposure)
        frame = ImageEnhance.Contrast(frame).enhance(1.06)
        frame = ImageEnhance.Color(frame).enhance(0.94)
        if index == 2:
            # macro frames get a duotone wash so the edit has tonal range
            tinted = ImageOps_colorize(frame, _mix(dark, (0, 0, 0), 0.2), light)
            frame = Image.blend(frame, tinted, 0.45)
        frame = _vignette(frame, 0.24)
        if narrate:
            frame = _photo_type_block(frame, name, narrate, index)
        path = out_dir / f"look_{index + 1:02d}_{name}.jpg"
        frame.save(path, quality=94, subsampling=1)
        out.append(
            {
                "path": str(path),
                "name": name,
                "treatment": f"crop {zoom:.2f}x · exposure {exposure:.2f}",
                "width": width,
                "height": height,
                "provenance": "source",
                "derived_from": str(source),
                "instructions": "derived from the uploaded photograph — no generative model",
            }
        )
    return out
